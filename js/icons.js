document.querySelectorAll('.preset-icon-btn').forEach(btn => {
  btn.addEventListener('click', () => {
    const key = btn.dataset.preset;
    const preset = PRESET_ICONS[key];
    if (!preset) return;

    pushHistory();
    const presetName = (typeof t === 'function' ? t('preset_name_' + key) : null) || preset.name;
    const newBitmap = {
      id: generateId(),
      type: 'bitmap',
      name: presetName,
      x: Math.round((SCREEN_WIDTH - preset.w) / 2),
      y: Math.round((SCREEN_HEIGHT - preset.h) / 2),
      w: preset.w,
      h: preset.h,
      origW: preset.w,
      origH: preset.h,
      threshold: 128,
      inverted: false,
      ditherMode: 'threshold',
      data: [...preset.data],
      visible: true
    };

    state.objects.push(newBitmap);
    selectObject(newBitmap.id);
    setActiveTool('select');
    renderAll();
    updateArduinoCode();
  });
});

